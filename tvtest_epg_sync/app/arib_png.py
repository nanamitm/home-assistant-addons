COLOR_TYPE_INDEXED = 3
IHDR_LENGTH = 13
# IHDR の本体は 幅4 + 高さ4 + ビット深度1 の次がカラータイプ。
IHDR_COLOR_TYPE_OFFSET = 9


class AribPngError(ValueError):
    """ロゴが PNG として読めない"""


def _chunk(kind: bytes, body: bytes) -> bytes:
    return (
        struct.pack(">I", len(body))
        + kind
        + body
        + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)
    )


_PLTE = _chunk(b"PLTE", bytes(v for r, g, b, _a in ARIB_PALETTE for v in (r, g, b)))
_TRNS = _chunk(b"tRNS", bytes(a for _r, _g, _b, a in ARIB_PALETTE))


def to_browser_png(data: bytes) -> bytes:
    """ARIB のロゴ PNG にパレットを補って返す。

    既にパレットを持つものや、インデックスカラーでないものはそのまま返す。
    """
    if not data.startswith(PNG_SIGNATURE):
        raise AribPngError("PNG ではありません")

    offset = 8
    parts: list[bytes] = [data[:8]]
    inserted = False

    while offset + 12 <= len(data):
        (length,) = struct.unpack_from(">I", data, offset)
        kind = data[offset + 4:offset + 8]
        end = offset + 12 + length
        if end > len(data):
            raise AribPngError("チャンクが途中で切れています")
        if kind in (b"PLTE", b"tRNS"):
            return data
        parts.append(data[offset:end])
        if kind == b"IHDR":
            if length != IHDR_LENGTH:
                raise AribPngError("IHDR の長さが不正です")
            if data[offset + 8 + IHDR_COLOR_TYPE_OFFSET] != COLOR_TYPE_INDEXED:
                return data
            parts.append(_PLTE)
            parts.append(_TRNS)
            inserted = True
        offset = end

    if not inserted:
        raise AribPngError("IHDR がありません")
    return b"".join(parts)
